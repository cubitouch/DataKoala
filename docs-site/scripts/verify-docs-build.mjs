// Verify the built documentation site exposes crawlable, metadata-complete
// content with JavaScript disabled, and that referenced assets resolve.
//
// Run after `pnpm docs:build`:
//   node docs-site/scripts/verify-docs-build.mjs
//
// Exits non-zero on any failed check so it can gate CI / deploys.

import { readFile, access } from 'node:fs/promises'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..')
const dist = resolve(root, 'docs-site', 'dist')
const htmlPath = resolve(dist, 'index.html')

const failures = []
const check = (name, ok, detail = '') => {
  if (ok) {
    console.log(`  ok  ${name}`)
  } else {
    failures.push(name)
    console.error(`FAIL  ${name}${detail ? ` — ${detail}` : ''}`)
  }
}

let html
try {
  html = await readFile(htmlPath, 'utf8')
} catch {
  console.error(`FAIL  dist/index.html not found at ${htmlPath}`)
  console.error('Run `pnpm docs:build` first.')
  process.exit(1)
}

console.log(
  'Verifying built docs-site/dist/index.html (JS-disabled crawlability + metadata)',
)

// 1. Meaningful content present without JavaScript.
check('H1 present', /<h1[^>]*>/.test(html))
check('substantive lede copy', /Explore data/.test(html))
check(
  'product capability links',
  /href="#workspace"/.test(html) && /href="#start"/.test(html),
)
check(
  'repo link',
  /href="https:\/\/github\.com\/cubitouch\/DataKoala"/.test(html),
)

// 2. Canonical / social / structured data.
check(
  'canonical',
  /rel="canonical"\s+href="https:\/\/cubitouch\.github\.io\/DataKoala\/"/.test(
    html,
  ),
)
check(
  'og:image absolute',
  /property="og:image"\s+content="https:\/\/cubitouch\.github\.io\/DataKoala\/og-image\.png"/.test(
    html,
  ),
)
check(
  'twitter:image absolute',
  /name="twitter:image"\s+content="https:\/\/cubitouch\.github\.io\/DataKoala\/og-image\.png"/.test(
    html,
  ),
)
check(
  'JSON-LD SoftwareSourceCode',
  /"@type":\s*"SoftwareSourceCode"/.test(html),
)

// 3. Sitemap + share image referenced and present in dist.
const sitemapPath = resolve(dist, 'sitemap.xml')
const ogPath = resolve(dist, 'og-image.png')
const sitemapOk = await access(sitemapPath).then(
  () => true,
  () => false,
)
const ogOk = await access(ogPath).then(
  () => true,
  () => false,
)
check('sitemap.xml present in dist', sitemapOk)
check('og-image.png present in dist', ogOk)
if (sitemapOk) {
  const sitemap = await readFile(sitemapPath, 'utf8')
  check(
    'sitemap points at canonical page',
    sitemap.includes('https://cubitouch.github.io/DataKoala/'),
  )
  check('sitemap has no stale lastmod', !/<lastmod>/.test(sitemap))
}

// 4. Stylesheet + static image assets referenced resolve in dist.
// Screenshots are generated by CI (`docs:screenshots`) before the build, so
// they are only required when present; static assets must always exist.
const assetRefs = [
  ...html.matchAll(/(?:src|href)="(\.\/[^"]+\.(?:css|png|jpg|jpeg))"/g),
].map((m) => m[1])
const missing = []
const missingScreenshots = []
for (const ref of new Set(assetRefs)) {
  const p = resolve(dist, ref.replace(/^\.\//, ''))
  const ok = await access(p).then(
    () => true,
    () => false,
  )
  if (!ok) {
    if (ref.startsWith('./screenshots/')) missingScreenshots.push(ref)
    else missing.push(ref)
  }
}
check(
  'all referenced stylesheet/static image assets exist in dist',
  missing.length === 0,
  missing.join(', '),
)
check(
  'screenshot references present',
  /\.\/screenshots\/docs-overview\.png/.test(html),
)
if (missingScreenshots.length) {
  console.log(
    `  note  ${missingScreenshots.length} screenshot(s) not in local dist (generated by CI docs:screenshots)`,
  )
}

if (failures.length) {
  console.error(`\n${failures.length} check(s) failed.`)
  process.exit(1)
}
console.log('\nAll checks passed.')
